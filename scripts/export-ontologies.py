"""Generate static downloads and the edge route table from the public catalog."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def outputs() -> dict[Path, bytes]:
    catalog = json.loads((ROOT / "catalog.json").read_text())
    result = {ROOT / "public/ontology/catalog.json": (ROOT / "catalog.json").read_bytes()}
    routes = {}
    for entry in catalog["ontologies"]:
        relative = entry["file"].removeprefix("ontologies/")
        result[ROOT / "public/ontology" / relative] = (ROOT / entry["file"]).read_bytes()
        route = {
            "id": entry["id"],
            "asset": f"/ontology/{relative}",
            "sha256": entry["sha256"],
            "versioned": True,
        }
        routes[entry["version_iri"]] = route
        if entry["version_iri"] == catalog["current"].get(entry["id"]):
            routes[entry["ontology_iri"]] = {**route, "versioned": False}
    result[ROOT / "edge/routes.mjs"] = (
        "// Generated by scripts/export-ontologies.py; do not edit.\n"
        + "export const routes = "
        + json.dumps(routes, indent=2)
        + ";\n"
    ).encode()
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, content in outputs().items():
        if args.check:
            if not path.is_file() or path.read_bytes() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    if stale:
        raise SystemExit("Stale ontology exports: " + ", ".join(stale))


if __name__ == "__main__":
    main()
